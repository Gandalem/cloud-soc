const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/opt/google/chrome/chrome',headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({httpCredentials:{username:'admin',password:'fixture-password'},viewport:{width:1536,height:1120}});
 const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:18765/');
 await page.locator('.incident').first().waitFor();
 assert.match(await page.locator('h1').innerText(),/종합상황판/);
 assert.equal(await page.locator('.institution tbody tr').count(),3);
 assert.equal(await page.locator('.score>strong').innerText(),'75');
 await page.screenshot({path:'output/soc-reference-overview.png',fullPage:true});
 await page.locator('.incident').first().click();await page.getByRole('dialog').locator('dl').waitFor();
 assert.match(await page.getByRole('dialog').innerText(),/반복된 인증 실패/);
 assert.match(await page.getByRole('dialog').getByRole('link',{name:/사고 조사로 이동/}).getAttribute('href'),/case=00000000000000000000000000000001/);
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'output/soc-reference-detail.png',fullPage:false});
 await page.keyboard.press('Escape');assert.equal(await page.getByRole('dialog').count(),0);
 const mapResponse=page.waitForResponse(r=>r.url().includes('/api/overview?')&&r.url().includes('organization='));
 await page.locator('.org-map-list button').filter({hasText:'연구소'}).click();
 assert.equal((await (await mapResponse).json()).cases.groups[0].organization,'연구소');
 await page.locator('.institution tbody tr').waitFor();
 assert.equal(await page.getByLabel('기관',{exact:true}).inputValue(),'연구소');
 await page.getByLabel('기관',{exact:true}).selectOption('본사');await page.getByLabel('조회 기간',{exact:true}).selectOption('7');
 const filtered=page.waitForResponse(r=>r.url().includes('/api/overview?')&&r.url().includes('organization='));
 await page.getByRole('button',{name:'조회',exact:true}).click();const response=await filtered;const value=await response.json();
 assert.equal(value.cases.total,2);assert.equal(value.cases.groups[0].organization,'본사');
 await page.locator('.incident').first().waitFor();assert.equal(await page.locator('.institution tbody tr').count(),1);
 assert.equal(await page.locator('.score>strong').innerText(),'61');
 assert.ok(Date.parse(value.operations.end)-Date.parse(value.operations.start)===7*86400000);
 await page.setViewportSize({width:390,height:844});await page.getByRole('button',{name:'메뉴 열기'}).click();
 assert.ok(await page.getByRole('navigation',{name:'공통 메뉴'}).isVisible());
 await page.getByRole('button',{name:'메뉴 닫기'}).click();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.screenshot({path:'output/soc-reference-mobile.png',fullPage:true});
 await page.route('**/api/overview?*',route=>route.fulfill({status:503,contentType:'application/json',body:'{"error":"fixture failure"}'}));
 await page.getByRole('button',{name:'새로고침',exact:true}).click();await page.getByRole('alert').waitFor();
 assert.match(await page.getByRole('alert').innerText(),/자료를 불러오지 못했습니다/);
 assert.equal(await page.locator('.metric>strong').first().innerText(),'—건');
 assert.equal(await page.locator('.score>strong').innerText(),'—');
 assert.equal(errors.length,0,errors.join('\n'));
 await browser.close();console.log('PASS: real Flask API, filters, case detail, Escape, mobile layout, failure state, no browser errors');
})().catch(e=>{console.error(e);process.exit(1)});
